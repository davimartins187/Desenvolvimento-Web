# Crie um script Python que leia dois numeros e tente mostrar a soma deles

numero01 = input('Digite o primeiro número:  ')
numero02 = input('Digite o segundo número:  ')

numero01Formatado = int(numero01)
numero02Formatado = int(numero02)
soma = numero02Formatado + numero01Formatado

print('A soma entre ' + numero01 + ' e ' +  numero02 + ' é ', soma)